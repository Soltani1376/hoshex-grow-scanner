HX.formatForCamera = () => {
  if(HX.state.goal!=='instagram') return 'متن یا ویدئوی ساده';
  if(HX.state.instagram.camera==='no') return 'ویدئوی بدون چهره با متن روی تصویر';
  if(HX.state.instagram.camera==='sometimes') return 'ویدئوی کوتاه؛ اگر خواستی بدون چهره هم می‌شود';
  return 'ویدئوی کوتاه رو به دوربین';
};

