HX.feedbackTypeFor = key => {
  if(String(key).startsWith('ig-')) return 'instagram';
  if(String(key).startsWith('content-') || key==='content') return 'content';
  if(String(key).startsWith('acquisition')) return 'acquisition';
  return key;
};

